import { prisma } from "@/lib/db";
import { requireWorkspaceServer } from "@/lib/workspace";
import { Card, EmptyState, PageHeader } from "@/components/ui";
import { BookOpen } from "lucide-react";
import ProvenanceBadge from "../goals/[id]/provenance-badge";
import FactsManager from "./facts-manager";

export const dynamic = "force-dynamic";

export default async function ContextPage() {
  const ctx = await requireWorkspaceServer();
  const facts = await prisma.profileFact.findMany({
    where: { workspaceId: ctx.workspace.id },
    orderBy: [{ category: "asc" }, { updatedAt: "desc" }],
  });

  return (
    <>
      <PageHeader
        title="Business context"
        description="The persistent facts agents reason over. Every value carries its provenance: verified facts, user-provided information, external observations and generated hypotheses are always distinguishable — and every value here can be inspected, corrected or deleted."
      />

      <Card className="rooted">
        <h2 className="flex items-center gap-2 font-medium text-charcoal"><BookOpen size={16} className="text-forest" aria-hidden="true" /> How provenance works</h2>
        <ul className="mt-2 grid gap-2 text-sm text-charcoal md:grid-cols-2">
          <li><ProvenanceBadge kind="verified" /> Confirmed by you (or a real source) — agents may treat it as ground truth.</li>
          <li><ProvenanceBadge kind="user_provided" /> You stated it — used as context, not independently verified.</li>
          <li><ProvenanceBadge kind="external_observation" /> Recorded from outside data with its source.</li>
          <li><ProvenanceBadge kind="hypothesis" /> Generated by an agent — unvalidated, always labelled in prompts and outputs.</li>
        </ul>
        <p className="mt-3 text-xs text-charcoal-soft">
          Correcting a value marks it as a user correction and resets verification honestly. Marking it verified records who verified it and when.
        </p>
      </Card>

      <div className="mt-6">
        {facts.length === 0 ? (
          <EmptyState
            title="No recorded facts yet"
            body="Facts appear here when you add them below, or when agent tasks (research, strategy) store their hypotheses for inspection. The workflow also reads your workspace profile — that stays the primary context source."
          />
        ) : (
          <FactsManager initialFacts={facts.map((f) => ({ id: f.id, category: f.category, key: f.key, value: f.value, provenance: f.provenance, confidence: f.confidence, source: f.source, verifiedAt: f.verifiedAt ? f.verifiedAt.toISOString() : null, updatedAt: f.updatedAt.toISOString() }))} />
        )}
      </div>
    </>
  );
}
